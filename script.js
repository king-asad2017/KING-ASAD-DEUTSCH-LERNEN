KING_ASAD.checkLessonCounts = function () {

    const results = {};

    this.LEVELS.forEach(level => {
        const actual = this.lessonTitles[level].length;
        const expected = this.LESSON_COUNTS[level];

        results[level] = {
            expected: expected,
            actual: actual,
            correct: actual === expected
        };
    });

    return results;
};

